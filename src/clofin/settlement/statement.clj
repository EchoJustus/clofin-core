(defn- compact-instant
  "An instant rendered for use inside a reference: seconds precision, no
  punctuation a reader has to escape."
  [^Instant instant]
  (str/replace (str (.truncatedTo instant java.time.temporal.ChronoUnit/SECONDS)) #"[-:]" ""))

(defn statement-reference
  "The identity of a generated statement, derived from what it is a statement
  *of*.

  Deterministic, so asking for the same statement twice produces the same
  reference and the second ingestion is recognised as a replay rather than
  admitted as a second document. The perturbation class is part of it because a
  perturbed statement is a different document, and two different documents
  sharing one reference is the `409` case rather than the replay case."
  [{:keys [scheme currency period-start period-end perturbation]}]
  (str "SIM-STMT-" scheme "-" currency
       "-" (compact-instant period-start)
       "-" (compact-instant period-end)
       "-" (str/upper-case (str/replace perturbation "-" ""))))

(defn generate
  "The statement the simulated scheme would send for a period, as a document.

      (generate {:scheme \"SIM-RTGS\" :currency \"SGD\"
                 :period-start inst :period-end inst
                 :perturbation \"none\"
                 :items [{:batch-id … :instruction-id … :outcome …
                          :resolved-at … :amount …} …]})

  `items` are the settlement memberships the caller read for the period —
  `clofin.settlement.repository/resolved-items-for` produces them. Which of
  them the scheme would report, in what order, and with what on each line is
  decided here.

  Lines are ordered by their scheme reference and then numbered, so the same
  inputs produce byte-identical output whatever order the rows arrived in. The
  returned value is a **wire document**: string keys, ready to be handed to a
  caller or posted straight back to `POST /reconciliation-statements`."
  [{:keys [scheme currency period-start period-end perturbation items]}]
  (let [class (assert-perturbation! perturbation)
        lines (->> items
                   (filter #(reportable? % period-start period-end))
                   (map item->line)
                   (sort-by :scheme-reference)
                   vec
                   (perturb class currency period-start))]
    {"format"             statement/format-name
     "formatVersion"      statement/format-version
     ;; Stated in the document itself, not only in the API description: a
     ;; statement saved to a file and read a year later must still say what it
     ;; is. Every other CloFin document that describes simulated activity
     ;; carries the same flag.
     "simulated"          true
     "scheme"             scheme
     "currency"           currency
     "statementReference" (statement-reference {:scheme scheme :currency currency
                                                :period-start period-start
                                                :period-end period-end
                                                :perturbation class})
     "periodStart"        (str period-start)
     "periodEnd"          (str period-end)
     "perturbation"       class
     "lines"
     (into []
           (map-indexed
            (fn [i line]
              (cond-> {"lineNo"          (inc i)
                       "schemeReference" (:scheme-reference line)
                       "lineType"        (:line-type line)
                       "amount"          (money/->wire (:amount line))
                       "valueDate"       (str (:value-date line))}
                (:payment-reference line)
                (assoc "paymentReference" (:payment-reference line)))))
           lines)}))
