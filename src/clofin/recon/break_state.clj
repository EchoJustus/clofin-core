;; The lifecycle
;; ---------------------------------------------------------------------------

(def transitions
  "State to `{event → next state}`. The diagram is generated from here, never
  the other way around.

  Every arrow has a driver, and that is a rule rather than a coincidence:
  `:assign` is driven by `POST /reconciliation-breaks/{id}/assignment` and
  `:resolve` by the transaction in which an adjustment posts. An arrow nothing
  drives is a schema path with no product path behind it (standing lesson
  **L-10**), and this table was written after the endpoints it describes
  precisely so that could not happen."
  {:open          {:assign :investigating, :resolve :resolved}
   :investigating {:resolve :resolved}
   :resolved      {}})

(def initial-state
  "Where a break begins. Matching opens breaks; a caller cannot create one at
  all, let alone in another state."
  :open)

(def states
  "Every state a break may hold. Sorted, so error detail and generated
  documentation are stable between runs. Identical to
  `recon_break_state_known` in migration `0012`."
  (into (sorted-set) (keys transitions)))

(def events
  "Every event the lifecycle recognises, across all states."
  (into (sorted-set) (mapcat keys) (vals transitions)))

(defn- outgoing
  "The events permitted from `state`, as `{event → next state}`.

  An unrecognised state is a defect rather than a caller error — the column
  carries a check constraint listing exactly these three — so it is reported as
  one rather than being quietly treated as terminal. Treating an unknown state
  as terminal would refuse every operation on the row and look, from outside,
  exactly like a correctly resolved break."
  [state]
  (or (get transitions state)
      (err/invalid! (str "Unknown reconciliation break state: " state)
                    {:state (str state) :known (mapv name states)})))

(defn known?
  "True when `state` is a state the lifecycle recognises."
  [state]
  (contains? transitions state))

(defn terminal?
  "True when no event leaves `state`.

  **Derived from the table rather than declared**, so a state that acquires an
  outgoing arrow stops being terminal in the same commit that gives it one —
  and the generated diagram stops drawing it as terminal in that commit too."
  [state]
  (empty? (outgoing state)))

(def terminal-states
  "The terminal set, derived. Never a second list: a hand-kept copy is the thing
  that goes stale while every test that reads it keeps passing."
  (into (sorted-set) (filter terminal?) states))

(defn permitted-events
  "The events `state` allows, sorted."
  [state]
  (into (sorted-set) (keys (outgoing state))))

(defn permitted?
  "True when `event` may be applied to `state`."
  [state event]
  (contains? (outgoing state) event))

(defn transition
  "The state reached by applying `event` to `state`.

  Throws a `:conflict` naming the attempted transition and what would have been
  permitted instead. A caller that has been refused needs to know which of its
  assumptions was wrong — `409` alone leaves it guessing between \"somebody
  already resolved this\" and \"this break was never yours\", which are very
  different situations for whoever is holding it."
  [state event]
  (or (get (outgoing state) event)
      (err/conflict!
       (str "Cannot " (name event) " a reconciliation break that is " (name state))
       {:break-state (name state)
        :attempted   (name event)
        :permitted   (mapv name (permitted-events state))})))

;; ---------------------------------------------------------------------------
;; A rule about state that is not a transition
;; ---------------------------------------------------------------------------

(def reassignable-states
  "States in which a break's assignee may be changed **without** moving it.

  `:investigating` only. Assigning an `open` break is the `:assign` transition —
  it is how a break becomes investigated — so it is an arrow rather than a
  member here; and a `resolved` break has an owner of record that must not be
  rewritten, because who resolved what is the history an investigation reads.

  This lives beside the table rather than inside a handler for the reason
  `clofin.payments.state/mutable-states` does: a rule about state written into a
  handler is a rule the next handler restates differently."
  #{:investigating})

(defn reassignable?
  "True when a break in `state` may be reassigned in place."
  [state]
  (outgoing state)                    ; an unrecognised state is a defect, not a `false`
  (contains? reassignable-states state))

(defn assert-assignable!
  "Throw a `:conflict` unless a break in `state` may take a new assignee at all.

  A break is assignable when assigning it is a transition (`:assign` is
  permitted) **or** when it is reassignable in place. Both halves are read from
  the values above rather than from a status test, so the one endpoint that sets
  an assignee cannot drift from the lifecycle it drives."
  [state]
  (when-not (or (permitted? state :assign) (reassignable? state))
    (err/conflict!
     (str "Cannot assign a reconciliation break that is " (name state))
     {:break-state    (name state)
      :attempted      "assign"
      :assignable-in  (mapv name (sort (into (into (sorted-set) reassignable-states)
                                             (filter #(permitted? % :assign))
                                             states)))}))
  state)
