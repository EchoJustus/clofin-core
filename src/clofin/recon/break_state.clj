(ns clofin.recon.break-state
  "The reconciliation break lifecycle, held as data.

  `transitions` **is** the lifecycle — not a description of one. Every rule
  about which event may follow which state is in that map, and every function
  here reads it rather than restating it. This is the shape
  `clofin.payments.state` established and ADR-0014 records, copied deliberately
  rather than reinvented: a transition rule written as an `if` inside a service
  is the failure both namespaces exist to prevent, because the table stops being
  the truth and nobody finds out until an audit.

  Because the lifecycle is a value it is tested by **enumeration** rather than
  by sampling — `clofin.recon.break-state-test` walks every (state, event) pair,
  so a pair nobody thought to write a case for is still covered — and it is
  **drawn** from the same value: `docs/diagrams/reconciliation-break-lifecycle.md`
  is generated by `clofin.tools.diagrams` and checked in both directions
  (ADR-0020 RULE 1, ADR-0021).

  ## What a break is, and why the states are these three

  A break is a tracked, owned, ageing fact — `DOMAIN_MODEL.md` §1: *not* a
  discrepancy somebody will look at later. So:

  | State | Meaning |
  |---|---|
  | `open` | Discovered by matching and assigned, and nobody has picked it up |
  | `investigating` | An actor has taken it on and is working it |
  | `resolved` | Closed by a posted adjustment — terminal |

  **Assignment is the transition.** A break becomes investigated by somebody
  taking ownership of it, so `:assign` is one fact rather than two, and it emits
  one audit event. Re-assigning an already-investigated break leaves the state
  where it is and is therefore *not* an arrow: it is governed by
  `reassignable-states` below, the same way `clofin.payments.state/mutable-states`
  governs amending a draft.

  **`resolved` is reached only by a posted adjustment**, which is why the arrow
  is named `:resolve` and driven from
  `clofin.recon.service/post-adjustment!` and nowhere else. There is no
  \"written off\" state: nothing in this increment can drive one, and a state
  with no driver is a promise the product does not keep (standing lesson
  **L-10**).

  **Age is derived, never stored.** It is `now - opened-at`, computed by
  whoever reads the break — `clofin.recon.repository` does it in SQL, on the
  same connection as the read. A stored age is wrong the moment it is written,
  for the same reason a stored balance is (ADR-0008).

  Pure: no database, no clock, no identifier generation."
  (:require [clofin.error :as err]))

