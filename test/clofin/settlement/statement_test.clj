(ns clofin.settlement.statement-test
  "The simulated scheme's statement generator, and the ways it can be made
  wrong.

  Two properties matter here beyond the obvious ones. The generator is
  **deterministic** — the same request produces byte-identical output, including
  the statement reference, which is what makes re-ingesting one a replay rather
  than a second document. And it is **separate from the matcher**: this test
  asserts that separation from the source, because standing lesson **L-16** is
  the record of what agreement between a thing and itself is worth."
  (:require [clofin.money :as money]
            [clofin.recon.matching :as matching]
            [clofin.settlement.statement :as statement]
            [clojure.java.io :as io]
            [clojure.set :as set]
            [clojure.string :as str]
            [clojure.test :refer [deftest is testing]])
  (:import [java.time Instant]))

(def ^:private from (Instant/parse "2026-08-01T00:00:00Z"))
(def ^:private to   (Instant/parse "2026-09-01T00:00:00Z"))

(def ^:private batch #uuid "11111111-1111-4111-8111-111111111111")
(def ^:private alpha #uuid "22222222-2222-4222-8222-222222222222")
(def ^:private beta  #uuid "33333333-3333-4333-8333-333333333333")

(def ^:private items
  [{:batch-id batch :instruction-id alpha :outcome "settled"
    :resolved-at (Instant/parse "2026-08-12T10:00:00Z") :amount (money/of "SGD" 125000)}
   {:batch-id batch :instruction-id beta :outcome "returned"
    :resolved-at (Instant/parse "2026-08-13T10:00:00Z") :amount (money/of "SGD" 90000)}])

(defn- generate
  [& {:keys [perturbation rows] :or {perturbation "none" rows items}}]
  (statement/generate {:scheme "SIM-RTGS" :currency "SGD"
                       :period-start from :period-end to
                       :perturbation perturbation :items rows}))

(defn- lines [doc] (get doc "lines"))
(defn- line-types [doc] (mapv #(get % "lineType") (lines doc)))
(defn- references [doc] (mapv #(get % "paymentReference") (lines doc)))
(defn- minor-units [doc] (mapv #(get-in % ["amount" "minorUnits"]) (lines doc)))

;; ---------------------------------------------------------------------------
;; L-16 — the generator and the matcher are different things
;; ---------------------------------------------------------------------------

(deftest the-generator-shares-no-matching-logic-with-the-matcher
  (testing "read from the source, because a runtime check would see a transitive
            require the file does not declare — the reason
            `clofin.ledger.purity-test` reads `ns` forms too"
    (let [form (with-open [r (java.io.PushbackReader.
                              (io/reader "src/clofin/settlement/statement.clj"))]
                 (read {:read-cond :allow} r))
          requires (->> form
                        (drop 2)
                        (filter #(and (seq? %) (= :require (first %))))
                        (mapcat rest)
                        (map #(str (if (sequential? %) (first %) %)))
                        set)]
      (is (contains? requires "clofin.recon.statement")
          "it must know the format it emits — that dependency is the direction")
      (is (not (contains? requires "clofin.recon.matching"))
          "a statement generated by the matcher's own rules proves the matcher
           agrees with itself, which is not a fact about anything (L-16)")
      (is (not (contains? requires "clofin.recon.repository"))
          "and it must not read the ledger: the two sides derive the amount, the
           date and the kind of movement by different routes")
      (is (not-any? #(str/starts-with? % "clofin.recon.") (disj requires "clofin.recon.statement"))
          (str "unexpected reconciliation dependencies: "
               (pr-str (remove #{"clofin.recon.statement"}
                               (filter #(str/starts-with? % "clofin.recon.") requires))))))))

