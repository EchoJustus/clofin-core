(deftest the-same-request-produces-the-same-document
  (testing "including the reference — which is what makes re-ingesting one a
            replay rather than a second document"
    (is (= (generate) (generate)))
    (is (= (generate :rows (reverse items)) (generate))
        "and the order the rows arrived in is not part of the answer")))

(deftest lines-are-ordered-by-their-own-reference-and-then-numbered
  (let [doc (generate)]
    (is (= (sort (mapv #(get % "schemeReference") (lines doc)))
           (mapv #(get % "schemeReference") (lines doc))))))

(deftest a-perturbed-statement-is-a-different-document-with-a-different-identity
  (testing "two different documents sharing one reference is the 409 case, not
            the replay case — so the class is part of the reference"
    (let [references (into #{} (map #(get (generate :perturbation %) "statementReference"))
                           (keys statement/perturbation-classes))]
      (is (= (count statement/perturbation-classes) (count references))))))

(deftest a-different-period-is-a-different-statement
  (is (not= (get (generate) "statementReference")
            (get (statement/generate {:scheme "SIM-RTGS" :currency "SGD"
                                      :period-start from
                                      :period-end (Instant/parse "2026-10-01T00:00:00Z")
                                      :perturbation "none" :items items})
                 "statementReference"))))

;; ---------------------------------------------------------------------------
;; Perturbations
;; ---------------------------------------------------------------------------

(deftest every-perturbation-class-does-what-its-name-says
  (let [clean (generate)]
    (testing "none"
      (is (= (lines clean) (lines (generate :perturbation "none")))))

    (testing "missing-line drops the first"
      (let [doc (generate :perturbation "missing-line")]
        (is (= 1 (count (lines doc))))
        (is (= (rest (references clean)) (references doc)))))

    (testing "amount-mismatch moves the first line's amount by a stated delta"
      (let [doc (generate :perturbation "amount-mismatch")]
        (is (= (+ (first (minor-units clean)) statement/amount-mismatch-minor)
               (first (minor-units doc))))
        (is (= (rest (minor-units clean)) (rest (minor-units doc)))
            "and nothing else")))

    (testing "unknown-line appends a payment CloFin never issued"
      (let [doc (generate :perturbation "unknown-line")]
        (is (= 3 (count (lines doc))))
        (is (= statement/unseen-payment-reference (last (references doc))))
        (is (not-any? #{statement/unseen-payment-reference} (references clean)))))

    (testing "duplicate-line repeats a line under a second line reference"
      (let [doc (generate :perturbation "duplicate-line")]
        (is (= 3 (count (lines doc))))
        (is (= (first (references clean)) (last (references doc)))
            "same payment claimed twice")
        (is (= 3 (count (distinct (map #(get % "schemeReference") (lines doc)))))
            "under distinct line references, which is what a real duplicate looks
             like")))

    (testing "shifted-value-date moves the first line's date and no other"
      (let [doc (generate :perturbation "shifted-value-date")]
        (is (not= (get (first (lines clean)) "valueDate")
                  (get (first (lines doc)) "valueDate")))
        (is (= (get (second (lines clean)) "valueDate")
               (get (second (lines doc)) "valueDate")))))

    (testing "flipped-line-type swaps settlement and return"
      (let [doc (generate :perturbation "flipped-line-type")]
        (is (not= (first (line-types clean)) (first (line-types doc))))
        (is (contains? #{"settlement" "return"} (first (line-types doc))))
        (is (= (rest (line-types clean)) (rest (line-types doc))))))

    (testing "reference-stripped removes the end-to-end reference and nothing else"
      (let [doc (generate :perturbation "reference-stripped")]
        (is (nil? (get (first (lines doc)) "paymentReference")))
        (is (= (get-in (first (lines clean)) ["amount" "minorUnits"])
               (get-in (first (lines doc)) ["amount" "minorUnits"])))
        (is (= (get (first (lines clean)) "valueDate")
               (get (first (lines doc)) "valueDate")))))))

(deftest perturbing-an-empty-statement-is-not-an-error
  (testing "an empty statement is a real statement, and refusing to perturb one
            would turn a legitimate request into an error at the least useful
            moment"
    (doseq [class (keys statement/perturbation-classes)]
      (is (some? (generate :perturbation class :rows [])) class))))

(deftest an-unknown-perturbation-class-is-refused-by-name
  (let [t (try (statement/assert-perturbation! "make-it-worse") nil (catch Exception e e))]
    (is (some? t))
    (is (= :validation (:clofin/error (ex-data t))))
    (is (= (vec (sort (keys statement/perturbation-classes))) (:known (ex-data t)))))
  (is (= "none" (statement/assert-perturbation! nil))
      "the statement the simulation would really send is the default, and it has
       a name rather than being the absence of a request"))

(deftest every-class-names-the-break-it-is-expected-to-produce
  (doseq [[class {:keys [expected-break summary]}] statement/perturbation-classes]
    (is (not (str/blank? summary)) (str class " must say what it does"))
    (when expected-break
      (is (contains? matching/break-kinds expected-break)
          (str class " expects a break kind the matcher cannot produce")))))

(deftest every-break-kind-is-reachable-from-some-named-class
  ;; Standing lesson **L-10**: a break kind reachable only from a unit test
  ;; constructing values by hand is a schema path with no product path behind
  ;; it. `expectation-unmatched` is reached by `missing-line`; the rest have a
  ;; class each.
  (let [expected (into #{} (keep :expected-break) (vals statement/perturbation-classes))]
    (is (empty? (set/difference (set matching/break-kinds) expected))
        (str "break kinds no perturbation class produces: "
             (pr-str (set/difference (set matching/break-kinds) expected))))))

;; ---------------------------------------------------------------------------
;; The line reference, and the SIM- discipline
;; ---------------------------------------------------------------------------

(deftest every-reference-the-generator-emits-is-sim-prefixed
  (let [doc (generate :perturbation "unknown-line")]
    (is (str/starts-with? (get doc "statementReference") "SIM-"))
    (doseq [line (lines doc)]
      (is (str/starts-with? (get line "schemeReference") "SIM-")))
    (is (str/starts-with? statement/unseen-payment-reference "SIM-"))))

(deftest a-line-reference-is-the-statements-own-and-not-a-response-reference
  (testing "a statement is a separate document with its own line references;
            reusing the settlement response's would make it look like a second
            copy of that table"
    (doseq [line (lines (generate))]
      (is (str/starts-with? (get line "schemeReference") statement/line-reference-prefix)))))

(deftest the-end-to-end-reference-is-the-instruction-id
  (testing "which is what makes a returned payment's original and its retry
            unambiguous: they are different instructions with different ids
            (ADR-0019)"
    (is (= #{(str alpha) (str beta)} (set (references (generate)))))))
