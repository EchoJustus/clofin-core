(deftest an-unperturbed-statement-reports-every-outcome-the-scheme-reached
  (let [doc (generate)]
    (is (= "SIM-CLOFIN-RECON-STATEMENT" (get doc "format")))
    (is (= 1 (get doc "formatVersion")))
    (is (true? (get doc "simulated"))
        "stated in the document itself: a statement saved to a file and read a
         year later must still say what it is")
    (is (= 2 (count (lines doc))))
    (is (= #{"settlement" "return"} (set (line-types doc))))
    (is (= #{(str alpha) (str beta)} (set (references doc))))
    (is (= [1 2] (mapv #(get % "lineNo") (lines doc))))))

(deftest a-timed-out-item-produces-no-line-at-all-and-that-is-the-product
  (testing "a statement line saying `timed out` would be the scheme reporting
            CloFin's own decision to stop waiting back to it. The money is still
            in 1300-IN-TRANSIT and correctly absent here — the pair ADR-0018's
            clearing account exists to make visible"
    (let [doc (generate :rows (conj items
                                    {:batch-id batch :instruction-id (random-uuid)
                                     :outcome "timed-out"
                                     :resolved-at (Instant/parse "2026-08-14T10:00:00Z")
                                     :amount (money/of "SGD" 5000)}))]
      (is (= 2 (count (lines doc))))))
  (testing "and neither does an item with no outcome yet"
    (let [doc (generate :rows [{:batch-id batch :instruction-id (random-uuid)
                                :outcome nil :resolved-at nil
                                :amount (money/of "SGD" 5000)}])]
      (is (empty? (lines doc))))))

(deftest the-period-is-half-open
  (testing "so consecutive statements chain exactly rather than double-counting
            whatever landed on the boundary"
    (let [at-start {:batch-id batch :instruction-id (random-uuid) :outcome "settled"
                    :resolved-at from :amount (money/of "SGD" 1)}
          at-end   {:batch-id batch :instruction-id (random-uuid) :outcome "settled"
                    :resolved-at to :amount (money/of "SGD" 2)}]
      (is (= 1 (count (lines (generate :rows [at-start])))) "start is included")
      (is (= 0 (count (lines (generate :rows [at-end])))) "end is excluded"))))

(deftest an-empty-period-is-a-real-statement
  (testing "it says the scheme did nothing, which is a fact rather than an error"
    (let [doc (generate :rows [])]
      (is (empty? (lines doc)))
      (is (str/starts-with? (get doc "statementReference") "SIM-STMT-")))))

